let score = 0;

function loadQuiz() {
    const quizContainer = document.getElementById('quiz-container');
    document.getElementById('total-questions').innerText = quizData.length;

    quizData.forEach((q, qIndex) => {
        const card = document.createElement('div');
        card.className = 'question-card';
        card.id = `q-${qIndex}`;

        let optionsHTML = '';
        q.options.forEach((opt, oIndex) => {
            optionsHTML += `
                <li class="option-item" onclick="selectOption(${qIndex}, ${oIndex})">
                    ${opt}
                </li>
            `;
        });

        let explanationsHTML = '';
        q.explanations.forEach((exp, eIndex) => {
            const isCorrectExp = eIndex === q.correct;
            explanationsHTML += `
                <div class="explanation-item ${isCorrectExp ? 'correct-text' : 'wrong-text'}">
                    ${exp}
                </div>
            `;
        });

        card.innerHTML = `
            <div class="question-title">${q.question}</div>
            <ul class="options-list">
                ${optionsHTML}
            </ul>
            <div class="explanation-box" id="exp-${qIndex}">
                <div class="explanation-title">📌 เฉลยละเอียด:</div>
                ${explanationsHTML}
            </div>
        `;

        quizContainer.appendChild(card);
    });
}

function selectOption(qIndex, selectedIndex) {
    const qCard = document.getElementById(`q-${qIndex}`);
    const options = qCard.querySelectorAll('.option-item');
    const qData = quizData[qIndex];

    // ปิดการกดซ้ำในข้อนี้
    options.forEach(opt => opt.classList.add('disabled'));

    // ตรวจสอบคำตอบ
    if (selectedIndex === qData.correct) {
        options[selectedIndex].classList.add('selected-correct');
        score++;
        document.getElementById('score').innerText = score;
    } else {
        options[selectedIndex].classList.add('selected-wrong');
        options[qData.correct].classList.add('show-correct');
    }

    // แสดงกล่องเฉลย
    document.getElementById(`exp-${qIndex}`).classList.add('active');
}

